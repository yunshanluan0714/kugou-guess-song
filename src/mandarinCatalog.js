export function pickRandomQueriesForCategory(category = 'all', count = 3, customKeyword = '') {
  const trimmedCustom = String(customKeyword || '').trim();
  if (trimmedCustom) {
    return Array.from({ length: Math.min(count, 2) }, (_, idx) => ({
      keyword: trimmedCustom,
      category: category === 'all' ? 'classic' : category,
      page: idx === 0 ? 1 + Math.floor(Math.random() * 3) : 2 + Math.floor(Math.random() * 5)
    }));
  }

  const validCat = ['classic', 'chart', 'folk_rock', 'cantonese_ost'].includes(category)
    ? category
    : null;

  const artists = validCat
    ? MANDARIN_ARTIST_CATALOG.filter((a) => a.category === validCat)
    : MANDARIN_ARTIST_CATALOG;
  const themes = validCat
    ? MANDARIN_THEME_KEYWORDS.filter((t) => t.category === validCat)
    : MANDARIN_THEME_KEYWORDS;

  const queries = [];
  for (let i = 0; i < count; i += 1) {
    if (i % 3 === 2 && themes.length > 0) {
      const theme = themes[Math.floor(Math.random() * themes.length)];
      queries.push({
        keyword: theme.kw,
        category: theme.category,
        page: 1 + Math.floor(Math.random() * 4)
      });
    } else if (artists.length > 0) {
      const artist = artists[Math.floor(Math.random() * artists.length)];
      queries.push({
        keyword: artist.name,
        category: artist.category,
        page: 1 + Math.floor(Math.random() * 3)
      });
    }
  }
  return queries;
}
